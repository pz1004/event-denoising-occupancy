#!/usr/bin/env python3
"""Reproduce EDmamba's E-MLB MESR row (paper Table 2) with the official checkpoint.

Why this script has to exist: the released code **cannot** produce Table 2.
`pointcept/engines/test.py:481` has `compute_average_esr` commented out and the
function is defined nowhere; `configs/_base_/default_runtime.py:38` has the
`ESRinference` tester commented out too. The one E-MLB reader that does work,
`ESR_dataset`, additionally (a) sets `labels = polarity` because E-MLB is
unlabeled, and (b) hard-filters to 13 named scenes at ND00 only -- not the paper's
48 scenes x 4 ND levels. So the published MESR numbers cannot be regenerated by
running the repository as shipped.

What this script does instead, changing nothing about the model:

1. Loads the official checkpoint exactly as `reproduce_edmamba_dnd21.py` does
   (strict `load_state_dict`, same config, same seed).
2. Reads E-MLB `.aedat4` with `dv_processing`, the same library `ESR_dataset` uses,
   and splits into consecutive 10,240-event blocks like every other protocol here.
3. Applies the config's own two-stage test transform: 0.05 temporal-grid random
   sampling (`mode="train"`, as shipped) then exhaustive 0.1-grid partitioning,
   and averages softmax over fragments -- identical to the DND21 runner.
4. **Two retention regimes, reported side by side.**
   - `argmax`: keep iff `P(noise) < --noise-threshold` (default 0.5). This is the
     model's *own* decision; retention is an output, not a knob. Recorded per cell.
   - `--retentions`: keep the lowest-`P(noise)` fraction `r` within each
     10,240-event block, the identical rule `phase5_emlb_mesr.retain_mask` applies
     to the Native3D score. This puts EDmamba and Native3D on the **same retention
     axis**, which separates *ranking quality* from *where the operating point sits*
     -- the only way to compare them fairly, since Table 2 never states EDmamba's
     operating point and a 2-scene probe shows argmax keeps ~99% of events at ND00
     (MESR ~0.73, far below the published 0.976).
5. Scores the surviving events with the numpy ESR that Phase 5 verified
   **bit-exact** against the official `cuke-emlb` `EventStructuralRatio._calc_esr`,
   over consecutive 30,000-event slices (the official
   `evalEventStorePerNumber` default), averaged over sequences in a cell.

Raw MESR is recomputed alongside every cell as a regression check against
`phase5_emlb_mesr.json` / `phase6_emlb_adaptive.json`.

Event cap: uncapped E-MLB is ~2.7 B events, ~78x the DND21 test set, which the
DND21 timing (3,393 blocks in 357 s) puts at roughly 8 GPU-hours on this host. The
default cap keeps every row comparable at a fraction of that. For an apples-to-apples
table, re-run the Native3D rows under the identical cap with the existing scripts:

    python -m native3d_ssm.phase5_emlb_mesr    --max-events 300000 --output ...capped.json
    python -m native3d_ssm.phase6_emlb_adaptive --max-events 300000 --output ...capped.json

The recomputed Raw row appears in all three outputs and quantifies how much the cap
moves MESR at all.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
import time
from collections import OrderedDict
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import torch
import torch.nn.functional as F

PROJECT_ROOT = Path(__file__).resolve().parents[1]
EDMAMBA_ROOT = PROJECT_ROOT / "EDmamba"
POINTOPS_BUILD = EDMAMBA_ROOT / "libs/pointops/build/lib.linux-x86_64-cpython-38"
sys.path.insert(0, str(EDMAMBA_ROOT))
sys.path.insert(0, str(POINTOPS_BUILD))
sys.path.insert(0, str(PROJECT_ROOT))

ND_LEVELS = ("ND00", "ND04", "ND16", "ND64")
PARTS = ("D-END", "N-END")
SLICE = 30_000
BLOCK = 10_240

PAPER_RAW = {"D-END": {"ND00": 0.821, "ND04": 0.824, "ND16": 0.815, "ND64": 0.786},
             "N-END": {"ND00": 0.890, "ND04": 0.824, "ND16": 0.786, "ND64": 0.768}}
PAPER_EDMAMBA = {"D-END": {"ND00": 0.976, "ND04": 0.990, "ND16": 0.985, "ND64": 0.972},
                 "N-END": {"ND00": 1.002, "ND04": 1.025, "ND16": 1.082, "ND64": 1.089}}


def seed_everything(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def build_checkpoint_model(config_path: Path, checkpoint_path: Path) -> Tuple[torch.nn.Module, Dict]:
    """Identical to reproduce_edmamba_dnd21.build_checkpoint_model (strict load)."""

    from pointcept.models import build_model
    from pointcept.utils.config import Config

    cfg = Config.fromfile(str(config_path))
    model = build_model(cfg.model)
    checkpoint = torch.load(str(checkpoint_path), map_location="cpu")
    state = OrderedDict(
        (key[7:] if key.startswith("module.") else key, value)
        for key, value in checkpoint["state_dict"].items()
    )
    model.load_state_dict(state, strict=True)
    model = model.cuda().eval()
    metadata = {
        "checkpoint": str(checkpoint_path.resolve()),
        "checkpoint_epoch": int(checkpoint["epoch"]),
        "checkpoint_best_metric": float(checkpoint["best_metric_value"]),
        "trainable_parameters": int(
            sum(p.numel() for p in model.parameters() if p.requires_grad)),
    }
    return model, metadata


def esr(x: np.ndarray, y: np.ndarray, width: int, height: int) -> float:
    """Official E-MLB Event Structural Ratio (numpy, verified bit-exact in Phase 5)."""

    n_events = len(x)
    if n_events < 2:
        return float("nan")
    pixels = width * height
    counts = np.bincount(y.astype(np.int64) * width + x.astype(np.int64),
                         minlength=pixels).astype(np.float64)
    m = int(n_events * 2 / 3)
    eps = np.spacing(1)
    ntss = (counts * (counts - 1)).sum() / (n_events + eps) / (n_events - 1 + eps)
    ln = pixels - ((1 - m / n_events) ** counts).sum()
    return float(np.sqrt(ntss * ln))


def mesr(x: np.ndarray, y: np.ndarray, width: int, height: int,
         slice_size: int = SLICE) -> float:
    scores = [esr(x[i:i + slice_size], y[i:i + slice_size], width, height)
              for i in range(0, len(x) - slice_size + 1, slice_size)]
    return float(np.mean(scores)) if scores else float("nan")


def read_aedat4(path: Path, max_events: Optional[int]) -> Optional[np.ndarray]:
    """Same reader and same stable-sort timestamp repair as phase5_emlb_mesr."""

    import dv_processing as dv

    recording = dv.io.MonoCameraRecording(str(path))
    chunks: List[np.ndarray] = []
    total = 0
    while recording.isRunning():
        batch = recording.getNextEventBatch()
        if batch is None:
            continue
        array = batch.numpy()
        chunks.append(array)
        total += len(array)
        if max_events is not None and total >= max_events:
            break
    if not chunks:
        return None
    events = np.concatenate(chunks)
    if max_events is not None:
        events = events[:max_events]
    if len(events) > 1 and np.any(np.diff(events["timestamp"].astype(np.int64)) < 0):
        events = events[np.argsort(events["timestamp"], kind="mergesort")]
        read_aedat4.repairs += 1
    return events


read_aedat4.repairs = 0


def prepare_block(block: np.ndarray) -> Tuple[Dict, np.ndarray, int]:
    """Config's first test transform: 0.05 temporal grid, mode='train', as shipped."""

    from pointcept.datasets.transform import GridSample_V3

    timestamps = block["timestamp"].astype(np.int64)
    span = timestamps[-1] - timestamps[0]
    if span <= 0:
        return {}, np.empty(0, dtype=np.int64), 0
    normalized_time = (timestamps - timestamps.min()) / span
    coord = np.column_stack((block["x"].astype(np.float32),
                             block["y"].astype(np.float32),
                             normalized_time.astype(np.float32))).astype(np.float32)
    strength = ((block["polarity"].astype(np.int64) > 0).astype(np.float32) * 2 - 1
                ).reshape(-1, 1)
    data = {"coord": coord, "strength": strength,
            "segment": np.zeros(len(block), dtype=np.int64)}
    sampler = GridSample_V3(grid_size=0.05, hash_type="fnv", mode="train",
                            keys=("coord", "strength", "segment"),
                            return_inverse=True)
    data = sampler(data)
    inverse = data["inverse"].copy()
    return data, inverse, int(data["segment"].size)


def score_block(model: torch.nn.Module, block: np.ndarray) -> Tuple[np.ndarray, float]:
    """Per-event P(noise) for one 10,240-event block; same path as the DND21 runner."""

    from pointcept.datasets.transform import Collect, GridSample_V3, ToTensor
    from pointcept.datasets.utils import collate_fn

    data, inverse, sampled_size = prepare_block(block)
    if sampled_size == 0:
        return np.zeros(len(block), dtype=np.float32), 0.0
    voxelizer = GridSample_V3(grid_size=0.1, hash_type="fnv", mode="test",
                              keys=("coord", "strength"), return_grid_coord=True)
    fragments = voxelizer(data)
    to_tensor = ToTensor()
    collect = Collect(keys=("coord", "grid_coord", "index"),
                      feat_keys=("coord", "strength"))

    probabilities = torch.zeros((sampled_size, 2), device="cuda")
    counts = torch.zeros((sampled_size, 1), device="cuda")
    inference_seconds = 0.0
    for fragment in fragments:
        input_dict = collate_fn([collect(to_tensor(fragment))])
        input_dict = {k: (v.cuda(non_blocking=True) if isinstance(v, torch.Tensor) else v)
                      for k, v in input_dict.items()}
        index = input_dict["index"]
        torch.cuda.synchronize()
        start = time.perf_counter()
        with torch.inference_mode():
            logits = model(input_dict)["seg_logits"]
            part_probability = F.softmax(logits, dim=-1)
        torch.cuda.synchronize()
        inference_seconds += time.perf_counter() - start
        probabilities[index] += part_probability
        counts[index] += 1

    sampled_noise = (probabilities / counts.clamp(min=1))[:, 1].cpu().numpy()
    return sampled_noise[inverse].astype(np.float32), inference_seconds


def score_sequence(model: torch.nn.Module, events: np.ndarray) -> Tuple[np.ndarray, float]:
    """P(noise) per event over whole-sequence consecutive blocks."""

    noise_probability = np.zeros(len(events), dtype=np.float32)
    seconds = 0.0
    for start in range(0, len(events) - BLOCK + 1, BLOCK):
        chunk = events[start:start + BLOCK]
        scores, elapsed = score_block(model, chunk)
        noise_probability[start:start + BLOCK] = scores
        seconds += elapsed
    tail = (len(events) // BLOCK) * BLOCK
    if tail < len(events):
        # Trailing partial block: keep it (no decision) rather than drop events,
        # so Raw and filtered streams cover the identical event range.
        noise_probability[tail:] = 0.0
    return noise_probability, seconds


def retain_mask(scores: np.ndarray, retention: float, block: int = BLOCK) -> np.ndarray:
    """Keep the lowest-scoring `retention` fraction within each block.

    Byte-identical in behaviour to phase5_emlb_mesr.retain_mask, so the Native3D and
    EDmamba rows differ only in the score being ranked.
    """

    keep = np.zeros(len(scores), dtype=bool)
    for start in range(0, len(scores), block):
        chunk = scores[start:start + block]
        if len(chunk) == 0:
            continue
        n_keep = max(1, int(round(len(chunk) * retention)))
        order = np.argsort(chunk, kind="stable")[:n_keep]
        keep[start + order] = True
    return keep


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emlb-root", type=Path, default=PROJECT_ROOT / "E-MLB")
    parser.add_argument("--checkpoint", type=Path,
                        default=EDMAMBA_ROOT / "exp/ED24/EDmamba/model/model_best.pth")
    parser.add_argument("--config", type=Path,
                        default=EDMAMBA_ROOT / "configs/ED24/EDmamba.py")
    parser.add_argument("--max-events", type=int, default=300_000,
                        help="Per-sequence cap; 0 = uncapped (~8 GPU-hours).")
    parser.add_argument("--reps", nargs="+", type=int, default=[1, 2, 3])
    parser.add_argument("--max-scenes", type=int, default=None)
    parser.add_argument("--parts", nargs="+", default=list(PARTS))
    parser.add_argument("--nd-levels", nargs="+", default=list(ND_LEVELS))
    parser.add_argument("--noise-threshold", type=float, default=0.5,
                        help="Keep an event iff P(noise) < this. 0.5 = plain argmax.")
    parser.add_argument("--retentions", nargs="+", type=float,
                        default=[0.3, 0.5, 0.7, 0.9],
                        help="Fixed retention sweep on P(noise), matching the Native3D rows.")
    parser.add_argument("--width", type=int, default=346)
    parser.add_argument("--height", type=int, default=260)
    parser.add_argument("--seed", type=int, default=1024)
    parser.add_argument("--output", type=Path,
                        default=PROJECT_ROOT / "reproduction/results/emlb_edmamba_mesr.json")
    parser.add_argument("--hard-exit", action="store_true",
                        help="Bypass CUDA destructor cleanup (old CUDA 11.6 on WSL).")
    return parser.parse_args()


def build_payload(args, results, metadata, started) -> Dict:
    return {
        "what": "EDmamba official checkpoint applied to E-MLB, scored with bit-exact ESR",
        "why_not_released_code": (
            "compute_average_esr is commented out (test.py:481) and defined nowhere; "
            "ESRinference is commented out (default_runtime.py:38); ESR_dataset sets "
            "labels=polarity and hard-filters to 13 scenes at ND00 only. Table 2 is not "
            "regenerable by running the repo as shipped."),
        "protocol": {
            "block_size": BLOCK,
            "slice": SLICE,
            "first_grid_size": 0.05,
            "test_grid_size": 0.1,
            "aggregation": "mean ESR over 30,000-event slices, then mean over sequences",
            "retention_argmax": f"keep iff P(noise) < {args.noise_threshold} (model decides, not tuned)",
            "retention_sweep": args.retentions,
            "max_events_per_sequence": args.max_events,
            "reps": args.reps,
            "seed": args.seed,
            "sensor": [args.width, args.height],
        },
        "model": metadata,
        "environment": {
            "python": sys.version.split()[0],
            "torch": torch.__version__,
            "torch_cuda": torch.version.cuda,
            "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
        },
        "results": results,
        "timestamp_repairs": int(read_aedat4.repairs),
        "wall_seconds": time.perf_counter() - started,
    }


def main() -> None:
    args = parse_args()
    seed_everything(args.seed)
    started = time.perf_counter()
    model, metadata = build_checkpoint_model(args.config, args.checkpoint)
    print(f"loaded checkpoint epoch={metadata['checkpoint_epoch']} "
          f"params={metadata['trainable_parameters']}", flush=True)

    results: Dict[str, Dict[str, Dict]] = {}
    cap: Optional[int] = args.max_events if args.max_events > 0 else None

    for part in args.parts:
        root = args.emlb_root / part
        scenes = sorted(d.name for d in root.iterdir()
                        if d.is_dir() and not d.name.startswith("."))
        if args.max_scenes:
            scenes = scenes[:args.max_scenes]
        results[part] = {}
        for nd in args.nd_levels:
            raw_mesr, filtered_mesr, retentions = [], [], []
            sweep_mesr = {r: [] for r in args.retentions}
            inference_seconds = 0.0
            for scene in scenes:
                for rep in args.reps:
                    path = root / scene / f"{scene}-{nd}-{rep}.aedat4"
                    if not path.exists():
                        continue
                    events = read_aedat4(path, cap)
                    if events is None or len(events) < SLICE:
                        continue
                    x, y = events["x"], events["y"]
                    raw_mesr.append(mesr(x, y, args.width, args.height))
                    noise_probability, seconds = score_sequence(model, events)
                    inference_seconds += seconds
                    keep = noise_probability < args.noise_threshold
                    retentions.append(float(keep.mean()))
                    filtered_mesr.append(mesr(x[keep], y[keep], args.width, args.height))
                    for r in args.retentions:
                        mask = retain_mask(noise_probability, r)
                        sweep_mesr[r].append(mesr(x[mask], y[mask], args.width, args.height))
            cell = {
                "sequences": len(raw_mesr),
                "raw_mesr": float(np.nanmean(raw_mesr)) if raw_mesr else None,
                "edmamba_mesr": float(np.nanmean(filtered_mesr)) if filtered_mesr else None,
                "edmamba_mesr_by_retention": {str(r): (float(np.nanmean(v)) if v else None)
                                              for r, v in sweep_mesr.items()},
                "mean_retention": float(np.mean(retentions)) if retentions else None,
                "std_retention": float(np.std(retentions)) if retentions else None,
                "paper_raw": PAPER_RAW[part][nd],
                "paper_edmamba": PAPER_EDMAMBA[part][nd],
                "inference_seconds": inference_seconds,
            }
            results[part][nd] = cell
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(json.dumps(
                build_payload(args, results, metadata, started), indent=2, sort_keys=True) + "\n")
            print(f"{part} {nd}: raw={cell['raw_mesr']:.4f} (paper {cell['paper_raw']:.3f}) "
                  f"edmamba={cell['edmamba_mesr']:.4f} (paper {cell['paper_edmamba']:.3f}) "
                  f"retention={cell['mean_retention']:.3f}+-{cell['std_retention']:.3f} "
                  f"| sweep " + " ".join(f"r{r}={cell['edmamba_mesr_by_retention'][str(r)]:.4f}"
                                         for r in args.retentions)
                  + f" n={cell['sequences']}", flush=True)

    args.output.write_text(json.dumps(
        build_payload(args, results, metadata, started), indent=2, sort_keys=True) + "\n")
    print(f"\nWrote {args.output} in {time.perf_counter() - started:.1f}s", flush=True)
    if args.hard_exit:
        sys.stdout.flush()
        sys.stderr.flush()
        os._exit(0)


if __name__ == "__main__":
    main()
